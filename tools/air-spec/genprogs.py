#!/usr/bin/env python3
"""Build the SkyIOS Metal driver's program table from CoreAnimation's
metallib: for every 'VERTEX_KEY + FRAGMENT_KEY' line of a key list
(keys as the driver logs them: function[name=value ...]), specialise both
functions (airspec.py), translate them to GLSL (air2glsl.py), compile with
glslangValidator and skyprog (mesa ir3, in docker) and write one header.

usage: genprogs.py ca.ll keys.txt SkyPrograms.h
  needs: xcrun air-opt (Metal toolchain), glslangValidator, docker images
  skyios-mesadev / skyios-ir3c and the mesa tree in research/mesa-build
  (see tools/air-spec/README.md).
"""
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MESA = os.path.join(ROOT, 'research', 'mesa-build')
WORK = os.path.join(MESA, 'sky', 'gen')


def parse_key(k):
    m = re.match(r'^([\w.]+)(?:\[(.*)\])?$', k.strip())
    consts = {}
    for kv in (m.group(2) or '').split():
        n, v = kv.split('=')
        consts[n] = v
    return m.group(1), consts


def canon(name, consts):
    """the driver's key: name[sorted non-zero constants]"""
    parts = sorted('%s=%s' % (k, v) for k, v in consts.items() if v not in ('0', '0,0,0'))
    return '%s[%s]' % (name, ' '.join(parts)) if parts else name


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def main():
    ca, keyfile, out = sys.argv[1:4]
    shutil.rmtree(WORK, ignore_errors=True)
    os.makedirs(WORK)
    shutil.copy(os.path.join(HERE, 'skyprog.cc'), os.path.join(MESA, 'skyprog.cc'))
    shutil.copy(os.path.join(HERE, 'build-skyprog.sh'), os.path.join(MESA, 'build3.sh'))
    r = run(['docker', 'run', '--rm', '-v', MESA + ':/w', 'skyios-mesadev', 'sh', '/w/build3.sh'])
    if 'built' not in r.stdout:
        sys.exit('skyprog build failed:\n' + r.stdout[-3000:] + r.stderr[-3000:])

    pairs = []
    seen = set()
    for line in open(keyfile):
        line = line.split('#')[0].strip()
        if not line:
            continue
        vk, fk = [x.strip() for x in line.split(' + ')]
        v, f = parse_key(vk), parse_key(fk)
        key = (canon(*v), canon(*f))
        if key in seen:
            continue
        seen.add(key)
        pairs.append((key, v, f))

    ok = []
    for i, (key, v, f) in enumerate(pairs):
        name = 'skyp%d' % i
        base = os.path.join(WORK, name)
        try:
            for (fn, consts), suffix in ((v, 'v'), (f, 'f')):
                spec = ' '.join('%s=%s' % kv for kv in consts.items())
                r = run([sys.executable, os.path.join(HERE, 'airspec.py'), '-O', '%s:%s' % (ca, fn), spec])
                if r.returncode:
                    raise RuntimeError('airspec %s: %s' % (fn, r.stderr.strip()[-300:]))
                open('%s.%s.ll' % (base, suffix), 'w').write(r.stdout)
            r = run([sys.executable, os.path.join(HERE, 'air2glsl.py'), base + '.v.ll', base + '.f.ll', WORK, name])
            if r.returncode:
                raise RuntimeError(r.stderr.strip()[-300:])
            for st, ext in (('vs', 'vert'), ('fs', 'frag')):
                r = run(['glslangValidator', '-V', '--target-env', 'vulkan1.1', '-o', '%s.%s.spv' % (base, st),
                         '%s.%s' % (base, ext)])
                if r.returncode:
                    raise RuntimeError('glslang %s: %s' % (ext, r.stdout.strip()[-400:]))
            ok.append((name, key))
        except RuntimeError as e:
            print('%s  %s + %s: %s' % (name, key[0], key[1], e))

    # skyprog for all in one container
    script = ''.join('/w/build2/src/freedreno/ir3/skyprog %s /w/sky/gen/%s.vs.spv /w/sky/gen/%s.fs.spv '
                     '> /w/sky/gen/%s.h 2> /w/sky/gen/%s.err || echo FAIL %s\n' % (n, n, n, n, n, n) for n, _ in ok)
    open(os.path.join(WORK, 'skyprog.sh'), 'w').write(script)
    r = run(['docker', 'run', '--rm', '-v', MESA + ':/w', 'skyios-ir3c', 'sh', '/w/sky/gen/skyprog.sh'])
    failed = set(re.findall(r'FAIL (\w+)', r.stdout))

    hdr = ['// Generated by tools/air-spec/genprogs.py from %s, do not edit.' % os.path.basename(keyfile),
           '#include "SkyProg.h"', '']
    entries = []
    for name, key in ok:
        if name in failed:
            err = open(os.path.join(WORK, name + '.err')).read().strip().splitlines()
            print('%s  %s + %s: skyprog: %s' % (name, key[0], key[1], err[-1] if err else '?'))
            continue
        info = json.load(open(os.path.join(WORK, name + '.json')))
        hdr.append('// %s + %s' % key)
        hdr.append(open(os.path.join(WORK, name + '.h')).read())
        tex = ', '.join('0xff' if t == 'fb' else str(t) for t in info['tex'])
        samp = ', '.join('{%s, %#xull}' % ((str(s[1]), 0) if s[0] == 'metal' else ('0xff', s[1])) for s in info['samp'])
        entries.append('    {"%s", "%s", &%s, %d, %d, {%s}, {%s}, %d},' %
                       (key[0], key[1], name, len(info['tex']), len(info['samp']), tex, samp, info['fbfetch']))
    hdr.append('static const SkyProgEntry sky_prog_table[] = {')
    hdr += entries
    hdr.append('};')
    open(out, 'w').write('\n'.join(hdr) + '\n')
    print('%d of %d programs' % (len(entries), len(pairs)))


main()
